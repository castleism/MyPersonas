-- Phase 1 request-review intake. This migration is intentionally fail-closed:
-- the global gate starts paused and every persona starts disabled. It accepts a
-- bounded, CAPTCHA-verified request only through the service-role RPC, writes
-- its audit trail in the same transaction, and queues a notification record.
-- It does not send email, draft review copy, create affiliate links, or publish.

begin;

create extension if not exists citext with schema extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.product_review_global_controls (
  singleton smallint primary key default 1 check (singleton = 1),
  accepting_requests boolean not null default false,
  abuse_paused boolean not null default true,
  fingerprint_burst_limit integer not null default 3
    check (fingerprint_burst_limit between 1 and 20),
  fingerprint_daily_limit integer not null default 8
    check (fingerprint_daily_limit between 1 and 100),
  email_daily_limit integer not null default 5
    check (email_daily_limit between 1 and 50),
  persona_daily_limit integer not null default 50
    check (persona_daily_limit between 1 and 1000),
  global_burst_limit integer not null default 100
    check (global_burst_limit between 1 and 5000),
  global_daily_limit integer not null default 500
    check (global_daily_limit between 1 and 50000),
  updated_at timestamptz not null default now()
);

insert into public.product_review_global_controls (singleton)
values (1)
on conflict (singleton) do nothing;

create table if not exists public.product_review_settings (
  persona_id uuid primary key,
  owner uuid not null references public.profiles(id) on delete cascade,
  enabled boolean not null default false,
  destination_ledger_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  foreign key (persona_id, owner)
    references public.personas(id, owner) on delete cascade,
  foreign key (destination_ledger_id, owner)
    references public.account_ledger(id, owner) on delete restrict,
  check (not enabled or destination_ledger_id is not null)
);

create table if not exists public.product_review_requests (
  id uuid primary key default gen_random_uuid(),
  owner uuid not null references public.profiles(id) on delete cascade,
  persona_id uuid not null,
  requester_email extensions.citext,
  requester_name text,
  product_name text not null,
  product_url text,
  reason text,
  consent_to_reply boolean not null default false,
  marketing_consent boolean not null default false,
  status text not null default 'request_received'
    check (status in (
      'request_received', 'triaged', 'declined', 'owner_testing',
      'evidence_ready', 'persona_draft', 'owner_approved', 'published',
      'corrected_or_withdrawn'
    )),
  captcha_verified_at timestamptz not null,
  request_fingerprint text not null
    check (request_fingerprint ~ '^[0-9a-f]{64}$'),
  dedupe_key text not null check (dedupe_key ~ '^[0-9a-f]{64}$'),
  idempotency_key uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  retention_expires_at timestamptz not null default (now() + interval '180 days'),
  foreign key (persona_id, owner)
    references public.personas(id, owner) on delete cascade,
  unique (persona_id, idempotency_key),
  unique (id, owner, persona_id),
  check (char_length(product_name) between 1 and 160),
  check (product_name !~ '[[:cntrl:]<>]'),
  check (requester_name is null or (
    char_length(requester_name) between 1 and 100
    and requester_name !~ '[[:cntrl:]<>]'
  )),
  check (requester_email is null or (
    char_length(requester_email::text) between 3 and 320
    and requester_email::text !~ '[[:cntrl:]<>]'
  )),
  check (product_url is null or (
    char_length(product_url) between 9 and 2048
    and product_url ~ '^https://'
    and product_url !~ '[[:cntrl:]<>]'
  )),
  check (reason is null or (
    char_length(reason) between 1 and 1500
    and reason !~ '[[:cntrl:]<>]'
  )),
  check (not consent_to_reply or requester_email is not null),
  check (not marketing_consent or requester_email is not null),
  check (retention_expires_at > created_at)
);

create table if not exists public.product_review_events (
  id bigint generated by default as identity primary key,
  request_id uuid,
  owner uuid not null references public.profiles(id) on delete cascade,
  persona_id uuid not null,
  event_type text not null check (event_type in (
    'request_received', 'duplicate_suppressed', 'rate_limited',
    'notification_queued', 'state_changed', 'pii_erased'
  )),
  actor_type text not null default 'service'
    check (actor_type in ('service', 'owner', 'system')),
  details jsonb not null default '{}'::jsonb
    check (jsonb_typeof(details) = 'object' and octet_length(details::text) <= 4096),
  created_at timestamptz not null default now(),
  foreign key (persona_id, owner)
    references public.personas(id, owner) on delete cascade,
  foreign key (request_id, owner, persona_id)
    references public.product_review_requests(id, owner, persona_id)
    on delete set null (request_id)
);

create table if not exists public.product_review_notifications (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null,
  owner uuid not null references public.profiles(id) on delete cascade,
  persona_id uuid not null,
  destination_ledger_id uuid not null,
  status text not null default 'queued'
    check (status in (
      'queued', 'claimed', 'sent', 'failed', 'reconciliation_required',
      'cancelled'
    )),
  idempotency_key text not null unique,
  attempt_count integer not null default 0 check (attempt_count between 0 and 20),
  available_at timestamptz not null default now(),
  claimed_at timestamptz,
  provider_message_id_hash text,
  last_error_code text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (request_id),
  foreign key (request_id, owner, persona_id)
    references public.product_review_requests(id, owner, persona_id)
    on delete cascade,
  foreign key (destination_ledger_id, owner)
    references public.account_ledger(id, owner) on delete restrict,
  check (provider_message_id_hash is null or provider_message_id_hash ~ '^[0-9a-f]{64}$'),
  check (last_error_code !~ '[[:cntrl:]<>]' and char_length(last_error_code) <= 120)
);

create table if not exists public.product_review_rate_limits (
  scope text not null check (scope in (
    'fingerprint_15m', 'fingerprint_day', 'email_day', 'persona_day',
    'global_15m', 'global_day'
  )),
  key_hash text not null check (key_hash ~ '^[0-9a-f]{64}$'),
  window_start timestamptz not null,
  hit_count integer not null default 1 check (hit_count > 0),
  expires_at timestamptz not null,
  primary key (scope, key_hash, window_start),
  check (expires_at > window_start)
);

create index if not exists product_review_requests_owner_created_idx
  on public.product_review_requests (owner, created_at desc);
create index if not exists product_review_requests_persona_dedupe_idx
  on public.product_review_requests (persona_id, dedupe_key, created_at desc);
create index if not exists product_review_events_owner_created_idx
  on public.product_review_events (owner, created_at desc);
create index if not exists product_review_notifications_queue_idx
  on public.product_review_notifications (available_at, created_at)
  where status = 'queued';
create index if not exists product_review_rate_limits_expiry_idx
  on public.product_review_rate_limits (expires_at);

alter table public.product_review_global_controls enable row level security;
alter table public.product_review_settings enable row level security;
alter table public.product_review_requests enable row level security;
alter table public.product_review_events enable row level security;
alter table public.product_review_notifications enable row level security;
alter table public.product_review_rate_limits enable row level security;

drop policy if exists "product review settings owner read" on public.product_review_settings;
create policy "product review settings owner read"
  on public.product_review_settings for select to authenticated
  using (auth.uid() = owner);

drop policy if exists "product review requests owner read" on public.product_review_requests;
create policy "product review requests owner read"
  on public.product_review_requests for select to authenticated
  using (auth.uid() = owner);

drop policy if exists "product review events owner read" on public.product_review_events;
create policy "product review events owner read"
  on public.product_review_events for select to authenticated
  using (auth.uid() = owner);

-- There are deliberately no browser policies for the global control, rate, or
-- notification tables. The notification table is a queue, not a send worker.
revoke all on public.product_review_global_controls from public, anon, authenticated;
revoke all on public.product_review_settings from public, anon, authenticated;
revoke all on public.product_review_requests from public, anon, authenticated;
revoke all on public.product_review_events from public, anon, authenticated;
